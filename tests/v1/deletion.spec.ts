import type { Page } from '@playwright/test';
import type { HomeProject } from '../../backend/src/home-types';
import { test, expect, identity, apiHome, fixtureHealth, origin, requestId, accessible, capture } from './helpers';

// Recording simultaneous 3D pages stalls teardown on this Windows host.
// Lifecycle checks retain screenshots and use the real Plan view when shared.
test.use({ video: 'off' });
test.beforeEach(async ({ request }) => fixtureHealth(request));

async function draft(page: Page) {
  await page.goto('/');
  const creating = page.waitForResponse(response => response.url().endsWith('/api/homes') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'New project', exact: true }).click();
  const response = await creating;
  expect(response.ok()).toBe(true);
  const home = (await response.json()).home as HomeProject;
  const headers = { Authorization: response.request().headers().authorization };
  await expect(page).toHaveURL(new RegExp('/projects/' + home.id + '$'));
  return { home, headers };
}

test('Trash — keyboard cancellation, failed save, lost response retry and restoration survive reload', async ({ page }, info) => {
  const { home, headers } = await draft(page);
  await page.goto('/');
  const remove = page.getByRole('button', { name: 'Delete ' + home.title, exact: true });
  await remove.focus();
  await page.keyboard.press('Enter');
  const dialog = page.getByRole('alertdialog', { name: `Move “${home.title}” to Trash?`, exact: true });
  await expect(dialog.getByRole('button', { name: 'Cancel', exact: true })).toBeFocused();
  await accessible(page);
  await capture(page, info, 'delete-confirmation', false);
  await page.keyboard.press('Escape');
  await expect(dialog).toHaveCount(0);
  await expect(remove).toBeFocused();
  expect((await page.request.get(origin + '/api/homes/' + home.id, { headers })).ok()).toBe(true);
  const submitted: string[] = [];
  let calls = 0;
  await page.route('**/api/homes/' + home.id + '/trash', async route => {
    calls++;
    submitted.push(route.request().postDataJSON().requestId);
    if (calls === 1) await route.fulfill({ status: 503, json: { error: { code: 'SAVE_FAILED', message: 'The change could not be saved. Try again.' } } });
    else if (calls === 2) {
      expect((await route.fetch()).ok()).toBe(true);
      await route.fulfill({ status: 503, json: { error: { code: 'RESPONSE_LOST', message: 'The response was interrupted. Try again to confirm.' } } });
    } else await route.continue();
  });
  await remove.click();
  await dialog.getByRole('button', { name: 'Move to Trash', exact: true }).click();
  await expect(dialog.getByRole('alert')).toContainText('could not be saved');
  expect((await page.request.get(origin + '/api/homes/' + home.id, { headers })).ok()).toBe(true);
  await dialog.getByRole('button', { name: 'Move to Trash', exact: true }).click();
  await expect(dialog.getByRole('alert')).toContainText('interrupted');
  await dialog.getByRole('button', { name: 'Move to Trash', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(remove).toHaveCount(0);
  expect(calls).toBe(3);
  expect(new Set(submitted).size).toBe(1);
  await page.reload();
  await expect(remove).toHaveCount(0);
  await page.getByRole('link', { name: 'Trash', exact: true }).click();
  const restore = page.getByRole('button', { name: 'Restore ' + home.title, exact: true });
  await expect(restore).toBeVisible();
  await accessible(page);
  await capture(page, info, 'saved-home-in-trash', false);
  await page.reload();
  await restore.click();
  await expect(restore).toHaveCount(0);
  await page.goto('/');
  await expect(remove).toBeVisible();
  await page.reload();
  await expect(remove).toBeVisible();
  const restored = await page.request.get(origin + '/api/homes/' + home.id, { headers });
  expect(restored.ok()).toBe(true);
  expect((await restored.json()).home).toMatchObject({ id: home.id, title: home.title, revisions: home.revisions });
  await info.attach('deletion-recovery', { contentType: 'application/json', body: JSON.stringify({ simulatedFailures: ['before save', 'after actual save'], requestCount: calls, uniqueRequestIds: new Set(submitted).size, restoredSameHome: true }) });
});

test('Trash — Firestore preserves shared records and fences access, delayed delete and stale restore', async ({ request }, info) => {
  test.skip(info.project.name !== 'desktop', 'Firestore API contract is covered once; UI runs on every viewport.');
  const owner = await identity(request), client = await identity(request), stranger = await identity(request);
  const home = await apiHome(request, owner);
  const opened = await request.post(origin + '/api/homes/' + home.id + '/room', { headers: owner, data: { requestId: requestId() } });
  expect(opened.ok()).toBe(true);
  const shared = await opened.json(), roomId = shared.room.id;
  const roomPath = origin + '/api/rooms/' + roomId, sharedPath = roomPath + '/home';
  expect((await request.post(origin + '/api/rooms/join', { headers: client, data: { joinCode: shared.joinCode } })).ok()).toBe(true);
  expect((await request.post(sharedPath + '/messages', { headers: client, data: { requestId: requestId(), baseRevisionId: home.headRevisionId, selection: { kind: 'home' }, askAssistant: false, text: 'Please preserve this original conversation.' } })).ok()).toBe(true);
  for (const [headers, action] of [[client, 'accept'], [owner, 'approve']] as const) expect((await request.post(sharedPath + '/' + action, { headers, data: { requestId: requestId(), revisionId: home.headRevisionId } })).ok()).toBe(true);
  const agreed = await request.post(sharedPath + '/agreements', { headers: owner, data: { requestId: requestId(), revisionId: home.headRevisionId } });
  expect(agreed.ok()).toBe(true);
  const before = await agreed.json();
  expect(before.agreements).toHaveLength(1);
  const exportPath = sharedPath + '/agreements/' + before.agreements[0].id + '/export';
  const markdown = await (await request.get(exportPath, { headers: client })).text();
  const deletion = { requestId: requestId(), baseRevisionId: home.headRevisionId };
  expect((await request.get(origin + '/api/trash')).status()).toBe(401);
  expect((await request.post(origin + '/api/homes/' + home.id + '/trash', { data: deletion })).status()).toBe(401);
  expect((await request.post(origin + '/api/homes/' + home.id + '/trash', { headers: stranger, data: deletion })).status()).toBe(404);
  expect([403, 404]).toContain((await request.post(roomPath + '/trash', { headers: client, data: { requestId: requestId() } })).status());
  const removed = await request.post(origin + '/api/homes/' + home.id + '/trash', { headers: owner, data: deletion });
  expect(removed.ok()).toBe(true);
  const item = (await removed.json()).item;
  expect(item).toMatchObject({ kind: 'home', id: home.id, roomId });
  expect((await (await request.get(origin + '/api/homes', { headers: owner })).json()).homes).toEqual([]);
  expect((await (await request.get(origin + '/api/trash', { headers: owner })).json()).items).toHaveLength(1);
  expect((await (await request.get(origin + '/api/trash', { headers: stranger })).json()).items).toEqual([]);
  for (const [path, headers] of [[origin + '/api/homes/' + home.id, owner], [sharedPath, client], [roomPath, owner], [exportPath, client]] as const) expect((await request.get(path, { headers })).status()).toBe(404);
  expect((await request.post(roomPath + '/messages', { headers: client, data: { requestId: requestId(), text: 'A late message must not save.' } })).status()).toBe(404);
  const restore = { kind: item.kind, id: item.id, trashId: item.trashId, requestId: requestId() };
  expect((await request.post(origin + '/api/trash/restore', { headers: stranger, data: restore })).status()).toBe(404);
  expect((await request.post(origin + '/api/trash/restore', { headers: owner, data: restore })).ok()).toBe(true);
  await request.post(origin + '/api/homes/' + home.id + '/trash', { headers: owner, data: deletion });
  const reopened = await request.get(sharedPath, { headers: client });
  expect(reopened.ok()).toBe(true);
  const after = await reopened.json();
  expect(after.home.scene).toEqual(before.home.scene);
  expect(after.home.revisions).toEqual(before.home.revisions);
  expect(after.room.messages).toEqual(before.room.messages);
  expect(after.decisions).toEqual(before.decisions);
  expect(after.agreements).toEqual(before.agreements);
  expect(after.room.observer.callsUsed).toBe(before.room.observer.callsUsed);
  expect(await (await request.get(exportPath, { headers: client })).text()).toBe(markdown);
  expect((await request.post(origin + '/api/rooms/join', { headers: stranger, data: { joinCode: shared.joinCode } })).ok()).toBe(false);
  expect((await request.post(roomPath + '/trash', { headers: owner, data: { requestId: requestId() } })).ok()).toBe(true);
  expect((await request.post(origin + '/api/trash/restore', { headers: owner, data: { ...restore, requestId: requestId() } })).status()).toBe(409);
  expect((await request.get(sharedPath, { headers: client })).status()).toBe(404);
  await info.attach('firestore-trash-preservation', { contentType: 'application/json', body: JSON.stringify({ exactScene: true, exactRevisions: true, exactMessages: true, exactDecisions: true, exactAgreements: true, exactExport: true, delayedDeleteFenced: true, staleRestoreFenced: true }) });
});

test('Trash — legacy shared room deletion and restore preserve the source project', async ({ page }, info) => {
  test.skip(info.project.name === 'narrow', 'Narrow viewport exercises the primary home deletion flow.');
  const { headers } = await draft(page);
  const source = { name: 'Preserved scope room', scope: 'Kitchen lighting installation is included in the agreed scope.', messages: 'The client requested a separate quote for display lights.' };
  const created = await page.request.post(origin + '/api/projects', { headers, data: source });
  expect(created.ok()).toBe(true);
  const project = (await created.json()).project;
  const opened = await page.request.post(origin + '/api/projects/' + project.id + '/room', { headers, data: {} });
  expect(opened.ok()).toBe(true);
  const room = (await opened.json()).room;
  await page.goto('/rooms/' + room.id);
  await page.getByRole('button', { name: 'Delete ' + room.name, exact: true }).click();
  const dialog = page.getByRole('alertdialog', { name: `Move “${room.name}” to Trash?`, exact: true });
  await expect(dialog.getByRole('button', { name: 'Cancel', exact: true })).toBeFocused();
  await dialog.getByRole('button', { name: 'Move to Trash', exact: true }).click();
  await expect(page).toHaveURL(/\/trash(?:\?.*)?$/);
  const restore = page.getByRole('button', { name: 'Restore ' + room.name, exact: true });
  await expect(restore).toBeVisible();
  await accessible(page);
  await capture(page, info, 'legacy-room-trash', false);
  await restore.click();
  await expect(restore).toHaveCount(0);
  await page.goto('/rooms/' + room.id);
  await expect(page.getByRole('button', { name: 'Delete ' + room.name, exact: true })).toBeVisible();
  const original = await page.request.get(origin + '/api/projects/' + project.id, { headers });
  expect(original.ok()).toBe(true);
  expect((await original.json()).project).toMatchObject(source);
});

test('Trash — shared studio exposes deletion to its owner and restores the same home', async ({ page, context }, info) => {
  test.skip(info.project.name === 'narrow', 'Narrow viewport exercises the primary home deletion flow.');
  const { home: empty, headers } = await draft(page);
  const chosen = await page.request.post(origin + '/api/homes/' + empty.id + '/template', { headers, data: { requestId: requestId(), baseRevisionId: null, templateId: 'compact-apartment' } });
  expect(chosen.ok()).toBe(true);
  const home = (await chosen.json()).home as HomeProject;
  const opened = await page.request.post(origin + '/api/homes/' + home.id + '/room', { headers, data: { requestId: requestId() } });
  expect(opened.ok()).toBe(true);
  const shared = await opened.json();
  await page.goto('/rooms/' + shared.room.id);
  await page.getByRole('button', { name: 'Plan', exact: true }).click();
  const client = await context.newPage();
  try {
    await client.goto('/client/rooms/' + shared.room.id + '#invite=' + encodeURIComponent(shared.inviteToken));
    await expect(client.getByRole('heading', { level: 1, name: home.title, exact: true })).toBeVisible();
    await client.getByRole('button', { name: 'Plan', exact: true }).click();
    await expect(client).not.toHaveURL(/#invite=/);
    await expect(client.getByRole('button', { name: 'Delete ' + home.title, exact: true })).toHaveCount(0);
    await page.bringToFront();
    await page.getByRole('button', { name: 'Delete ' + home.title, exact: true }).click();
    const dialog = page.getByRole('alertdialog', { name: `Move “${home.title}” to Trash?`, exact: true });
    await expect(dialog).toContainText(/shared|access/i);
    await capture(page, info, 'shared-home-delete-confirmation', false);
    await dialog.getByRole('button', { name: 'Move to Trash', exact: true }).click();
    await expect(page).toHaveURL(/\/trash(?:\?.*)?$/);
    await expect(page.getByRole('button', { name: 'Restore ' + home.title, exact: true })).toBeVisible();
    await client.reload();
    await expect(client.getByRole('main').getByRole('alert')).toContainText(/not found|unavailable|could not/i);
    await expect(client.getByRole('heading', { level: 1, name: home.title, exact: true })).toHaveCount(0);
    await page.bringToFront();
    const restore = page.getByRole('button', { name: 'Restore ' + home.title, exact: true });
    await restore.click();
    await expect(restore).toHaveCount(0);
    await expect(page.getByRole('status')).toContainText('restored');
    await page.goto('/rooms/' + shared.room.id);
    await expect(page.getByRole('button', { name: 'Delete ' + home.title, exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Plan', exact: true }).click();
    await client.reload();
    await expect(client.getByRole('heading', { level: 1, name: home.title, exact: true })).toBeVisible();
    await client.getByRole('button', { name: 'Plan', exact: true }).click();
    const restored = await page.request.get(origin + '/api/homes/' + home.id, { headers });
    expect((await restored.json()).home.scene).toEqual(home.scene);
  } finally { await client.close(); }
});
